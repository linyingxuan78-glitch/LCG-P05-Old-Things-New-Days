# Simple lexical preflight - not a GDScript engine/parser.
def check_balance(text,name):
    stack=[]
    string_start=None
    pairs={')':'(',']':'[','}':'{'}
    line=1; col=0; state='normal'; slash=False; at=0
    for c in text:
        if c=='\n': line+=1; col=0
        else: col+=1
        if state=='comment':
            if c=='\n': state='normal'
            continue
        if state=='str':
            if c=="\n": errors.append(f"{name}:{line}: newline inside double-quoted string started at {string_start}")
            if slash: slash=False
            elif c=='\\': slash=True
            elif c=='"': state='normal'
            continue
        if c=='#': state='comment';continue
        if c=='"': state='str';string_start=line;continue
        if c in '([{': stack.append((c,line,col))
        elif c in ')]}':
            if not stack or stack[-1][0]!=pairs[c]:
                errors.append(f'{name}:{line}:{col} bracket mismatch {c}')
                return
            stack.pop()
    if state=='str':errors.append(f'{name}: unterminated string')
    if stack:errors.append(f'{name}: unclosed {stack[-1]}')

for file in BASE.rglob('*.gd'):
    check_balance(file.read_text(encoding="utf-8"),str(file.relative_to(BASE)))

# Check resource names and files.
refs=set(re.findall(r'res://([^"\n]+)', '\n'.join(x.read_text(encoding="utf-8") for x in BASE.rglob('*.gd'))))
refs.update(re.findall(r'path="res://([^"\n]+)"',(BASE/'main.tscn').read_text(encoding="utf-8")))
missing=[]
for ref in refs:
    if '%' in ref:continue
    # Generated by tools/generate_engine_notices.gd only during Godot native build.
    # Missing at source stage is expected; the Windows exporter fails closed if absent.
    if ref == 'licenses/GODOT_BINARY_DEPENDENCIES.txt':continue
    if not (BASE/ref).exists():missing.append(ref)
if missing:errors.append('missing explicit resources: '+','.join(missing))
models=sorted((BASE/'assets/models').glob('*.glb'))
for model in models:
    if model.read_bytes()[:4]!=b'glTF':errors.append(f'invalid GLB header {model.name}')
if len(models)!=20:errors.append('expected 20 3D GLB assets, found '+str(len(models)))
audio=sorted((BASE/'assets/audio').glob('*.ogg'))
for sound in audio:
    if sound.read_bytes()[:4]!=b'OggS':errors.append(f'invalid OGG header {sound.name}')
if len(audio)!=8:errors.append('expected 8 OGG files, found '+str(len(audio)))

